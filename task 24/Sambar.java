class Sambar {
    String region;
    String mainIngredient;
    String spiceLevel;
    double quantity;
    boolean veg;
    String taste;

    Sambar(String region, String mainIngredient, String spiceLevel, double quantity, boolean veg, String taste) {
        this.region = region;
        this.mainIngredient = mainIngredient;
        this.spiceLevel = spiceLevel;
        this.quantity = quantity;
        this.veg = veg;
        this.taste = taste;
    }
}