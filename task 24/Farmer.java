class Farmer {
    String name;
    int age;
    String village;
    double landSize;
    String crop;
    boolean irrigation;

    Farmer(String name, int age, String village, double landSize, String crop, boolean irrigation) {
        this.name = name;
        this.age = age;
        this.village = village;
        this.landSize = landSize;
        this.crop = crop;
        this.irrigation = irrigation;
    }
}