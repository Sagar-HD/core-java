class Cap {
    String brand;
    String color;
    String size;
    double price;
    String material;
    boolean adjustable;

    Cap(String brand, String color, String size, double price, String material, boolean adjustable) {
        this.brand = brand;
        this.color = color;
        this.size = size;
        this.price = price;
        this.material = material;
        this.adjustable = adjustable;
    }
}