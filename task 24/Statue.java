class Statue {
    String name;
    String material;
    double height;
    String location;
    int year;
    String sculptor;

    Statue(String name, String material, double height, String location, int year, String sculptor) {
        this.name = name;
        this.material = material;
        this.height = height;
        this.location = location;
        this.year = year;
        this.sculptor = sculptor;
    }
}