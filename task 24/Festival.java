class Festival {
    String name;
    String country;
    String month;
    int duration;
    String type;
    boolean publicHoliday;

    Festival(String name, String country, String month, int duration, String type, boolean publicHoliday) {
        this.name = name;
        this.country = country;
        this.month = month;
        this.duration = duration;
        this.type = type;
        this.publicHoliday = publicHoliday;
    }
}