class Salt {
    String name;
    String formula;
    String color;
    double solubility;
    String taste;
    boolean edible;

    Salt(String name, String formula, String color, double solubility, String taste, boolean edible) {
        this.name = name;
        this.formula = formula;
        this.color = color;
        this.solubility = solubility;
        this.taste = taste;
        this.edible = edible;
    }
}