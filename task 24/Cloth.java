class Cloth {
    String type;
    String material;
    String color;
    String brand;
    double price;
    String size;

    Cloth(String type, String material, String color, String brand, double price, String size) {
        this.type = type;
        this.material = material;
        this.color = color;
        this.brand = brand;
        this.price = price;
        this.size = size;
    }
}