class Gum {
    String brand;
    String flavor;
    double price;
    int quantity;
    boolean sugarFree;
    String type;

    Gum(String brand, String flavor, double price, int quantity, boolean sugarFree, String type) {
        this.brand = brand;
        this.flavor = flavor;
        this.price = price;
        this.quantity = quantity;
        this.sugarFree = sugarFree;
        this.type = type;
    }
}